-- 1. Clean up duplicate test rows generated by fallback loops during failed imports
DELETE FROM public.program_levels
WHERE code IN ('UNDERGRADUATE-2', 'UNDERGRADUATE-3', 'GRADUATE-2', 'GRADUATE-3', 'DOCTORATE-2', 'DOCTORATE-3')
  AND NOT EXISTS (
    SELECT 1 FROM public.programs WHERE program_level_id = public.program_levels.id
  );

-- 2. Add unique index on label (case-insensitive)
CREATE UNIQUE INDEX IF NOT EXISTS uidx_program_levels_label
ON public.program_levels (lower(btrim(label)))
WHERE (deleted_at IS NULL);

CREATE UNIQUE INDEX IF NOT EXISTS uidx_course_types_label
ON public.course_types (lower(btrim(label)))
WHERE (deleted_at IS NULL);

-- 3. Update fn_create_program_level to reject duplicates rather than silently appending sequence
CREATE OR REPLACE FUNCTION public.fn_create_program_level(
    p_code text,
    p_label text,
    p_description text DEFAULT NULL::text
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO 'public'
AS $function$
DECLARE
    v_trimmed_label text;
    v_final_code text;
    v_seq int := 1;
BEGIN
    IF auth.uid() IS NOT NULL THEN
        PERFORM public.fn_assert_role('Dean', 'Admin');
    END IF;

    v_trimmed_label := btrim(COALESCE(p_label, ''));
    IF v_trimmed_label = '' THEN
        RETURN jsonb_build_object('success', false, 'message', 'Program level name (label) is required');
    END IF;

    IF EXISTS (
        SELECT 1 FROM public.program_levels
        WHERE lower(label) = lower(v_trimmed_label)
        AND deleted_at IS NULL
    ) THEN
        RETURN jsonb_build_object('success', false, 'message', 'Program level name already exists: ' || v_trimmed_label);
    END IF;

    v_final_code := upper(btrim(COALESCE(p_code, '')));
    IF v_final_code = '' THEN
        v_final_code := public.fn_generate_acronym(v_trimmed_label, 'LVL');
        IF EXISTS (
            SELECT 1 FROM public.program_levels
            WHERE lower(code) = lower(v_final_code) AND deleted_at IS NULL
        ) THEN
            v_seq := 2;
            WHILE EXISTS (
                SELECT 1 FROM public.program_levels
                WHERE lower(code) = lower(v_final_code || '-' || v_seq::text) AND deleted_at IS NULL
            ) LOOP
                v_seq := v_seq + 1;
            END LOOP;
            v_final_code := v_final_code || '-' || v_seq::text;
        END IF;
    ELSE
        IF EXISTS (
            SELECT 1 FROM public.program_levels
            WHERE lower(code) = lower(v_final_code)
            AND deleted_at IS NULL
        ) THEN
            RETURN jsonb_build_object('success', false, 'message', 'Program level code already exists: ' || v_final_code);
        END IF;
    END IF;

    INSERT INTO public.program_levels (code, label, description, created_by)
    VALUES (v_final_code, v_trimmed_label, NULLIF(btrim(COALESCE(p_description, '')), ''), auth.uid());

    RETURN jsonb_build_object('success', true, 'message', 'Program level created successfully', 'code', v_final_code);
END;
$function$;

