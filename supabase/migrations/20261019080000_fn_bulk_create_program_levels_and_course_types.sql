-- 5. Bulk create program levels RPC
CREATE OR REPLACE FUNCTION public.fn_bulk_create_program_levels(p_program_levels jsonb)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO 'public'
AS $function$
DECLARE
    v_row JSONB;
    v_code TEXT;
    v_label TEXT;
    v_description TEXT;
    v_errors JSONB := '[]'::JSONB;
    v_success_count INTEGER := 0;
    v_row_num INTEGER := 0;
    v_seen_codes TEXT[] := ARRAY[]::TEXT[];
    v_seen_labels TEXT[] := ARRAY[]::TEXT[];
BEGIN
    IF auth.uid() IS NOT NULL THEN
        PERFORM public.fn_assert_role('Admin', 'Dean');
    END IF;

    FOR v_row IN SELECT * FROM jsonb_array_elements(p_program_levels)
    LOOP
        v_row_num := v_row_num + 1;
        v_label := TRIM(COALESCE(v_row->>'label', ''));
        v_code := UPPER(TRIM(COALESCE(v_row->>'code', '')));
        v_description := NULLIF(TRIM(COALESCE(v_row->>'description', '')), '');

        -- Validate label
        IF v_label = '' THEN
            v_errors := v_errors || jsonb_build_object(
                'row', v_row_num,
                'code', v_code,
                'message', 'Program level name (label) is required'
            );
            CONTINUE;
        END IF;

        -- Auto-generate code if empty
        IF v_code = '' THEN
            v_code := UPPER(public.fn_generate_acronym(v_label, 'LVL'));
        END IF;

        -- Check duplicate within current import batch
        IF lower(v_label) = ANY(v_seen_labels) THEN
            v_errors := v_errors || jsonb_build_object(
                'row', v_row_num,
                'code', v_code,
                'message', 'Duplicate program level name in import file: ' || v_label
            );
            CONTINUE;
        END IF;

        IF lower(v_code) = ANY(v_seen_codes) THEN
            v_errors := v_errors || jsonb_build_object(
                'row', v_row_num,
                'code', v_code,
                'message', 'Duplicate program level code in import file: ' || v_code
            );
            CONTINUE;
        END IF;

        -- Check if already exists in database
        IF EXISTS (
            SELECT 1 FROM public.program_levels
            WHERE lower(label) = lower(v_label)
            AND deleted_at IS NULL
        ) THEN
            v_errors := v_errors || jsonb_build_object(
                'row', v_row_num,
                'code', v_code,
                'message', 'Program level name already exists: ' || v_label
            );
            CONTINUE;
        END IF;

        IF EXISTS (
            SELECT 1 FROM public.program_levels
            WHERE lower(code) = lower(v_code)
            AND deleted_at IS NULL
        ) THEN
            v_errors := v_errors || jsonb_build_object(
                'row', v_row_num,
                'code', v_code,
                'message', 'Program level code already exists: ' || v_code
            );
            CONTINUE;
        END IF;

        -- Insert record
        INSERT INTO public.program_levels (
            code,
            label,
            description,
            created_by
        )
        VALUES (
            v_code,
            v_label,
            v_description,
            auth.uid()
        );

        v_seen_labels := array_append(v_seen_labels, lower(v_label));
        v_seen_codes := array_append(v_seen_codes, lower(v_code));
        v_success_count := v_success_count + 1;
    END LOOP;

    RETURN jsonb_build_object(
        'success', true,
        'message', v_success_count || ' program level(s) created successfully',
        'provisioned_count', v_success_count,
        'errors', v_errors
    );
END;
$function$;

